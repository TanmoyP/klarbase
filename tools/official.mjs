// tools/official.mjs — read the OFFICIAL isle sources and render @klar/core's data module.
//
//   isles/official/chapters.json          chapters in play order; each lists its isle ids in order
//   isles/official/<chapter-key>/<id>.json one isle; chapter-key = chapter.id || chapter.theme
//
// core stays pure (no I/O), so it never reads these files: tools/author.mjs renders them into
// core/src/isle/official.js, and core/test/isles.mjs fails if that module is stale. `catch`
// (the designer's note) and the chapters' `isles` lists stay here — they are not shipped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SRC = path.join(ROOT, 'isles', 'official');
export const MODULE = path.join(ROOT, 'core', 'src', 'isle', 'official.js');

const chapterKey = c => c.id || c.theme;

// -> { chapters, isles } in play order; throws listing every layout problem
export function loadOfficial(dir = SRC){
  const errs = [], read = f => JSON.parse(fs.readFileSync(f, 'utf8'));
  const chapters = read(path.join(dir, 'chapters.json'));
  const isles = [], seen = new Set();
  for(const ch of chapters){
    const key = chapterKey(ch);
    if(!Array.isArray(ch.isles) || !ch.isles.length){ errs.push(`chapter "${key}" lists no isles`); continue; }
    const listed = new Set(ch.isles);
    for(const id of ch.isles){
      if(seen.has(id)){ errs.push(`isle "${id}" is listed twice`); continue; }
      seen.add(id);
      const f = path.join(dir, key, `${id}.json`);
      if(!fs.existsSync(f)){ errs.push(`${key}/${id}.json is listed in chapters.json but missing`); continue; }
      const doc = read(f);
      if(doc.id !== id) errs.push(`${key}/${id}.json has id "${doc.id}" — the file name must be "<id>.json"`);
      if((doc.chapter || doc.theme) !== key) errs.push(`${key}/${id}.json belongs to chapter "${doc.chapter || doc.theme}", not folder "${key}"`);
      if('catch' in doc && (typeof doc.catch !== 'string' || !doc.catch.trim())) errs.push(`${key}/${id}.json: "catch" must be a non-empty string`);
      isles.push(doc);
    }
    for(const f of fs.existsSync(path.join(dir, key)) ? fs.readdirSync(path.join(dir, key)) : [])
      if(!listed.has(f.replace(/\.json$/, ''))) errs.push(`${key}/${f} is not listed in chapters.json`);
  }
  for(const e of fs.readdirSync(dir, { withFileTypes:true }))
    if(e.isDirectory() && !chapters.some(c => chapterKey(c) === e.name)) errs.push(`folder ${e.name}/ is not a chapter in chapters.json`);
  if(errs.length) throw new Error('isles/official layout:\n  ' + errs.join('\n  '));
  return { chapters, isles };
}

// Deterministic JSON layout shared by the source files and the module: primitive arrays
// inline, except `rows` and `isles`, one entry per line (so a reorder is a one-line diff).
export function format(v, ind = '', key = ''){
  const pad = ind + '  ';
  if(Array.isArray(v)){
    if(!v.length) return '[]';
    if(v.every(x => x === null || typeof x !== 'object') && key !== 'rows' && key !== 'isles') return '[' + v.map(x => JSON.stringify(x)).join(', ') + ']';
    return '[\n' + v.map(x => pad + format(x, pad)).join(',\n') + '\n' + ind + ']';
  }
  if(v && typeof v === 'object')
    return '{\n' + Object.entries(v).map(([k, x]) => `${pad}${JSON.stringify(k)}: ${format(x, pad, k)}`).join(',\n') + '\n' + ind + '}';
  return JSON.stringify(v);
}

export function renderModule({ chapters, isles }){
  const strip = (o, k) => Object.fromEntries(Object.entries(o).filter(([x]) => x !== k));
  return `// GENERATED by tools/author.mjs from isles/official/ — do not edit. Edit the JSON there and re-run it.
// (Each isle's \`catch\` note and the chapters' isle lists stay in the JSON; they are not shipped.)
export const CHAPTERS = ${format(chapters.map(c => strip(c, 'isles')))};

export const CURATED_ISLES = ${format(isles.map(i => strip(i, 'catch')))};
`;
}
